// Generates docs/IMAGE-MANIFEST.md and docs/PHOTOGRAPHY-SHOT-LIST.md — every image on the site, its provenance
// and how to replace it.
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";

const catalog = readFileSync("src/data/catalog-data.ts", "utf8");
const re = /slug: "([^"]+)",\s*model: "([^"]+)",\s*category: "([^"]+)",\s*name: \{ en: "([^"]+)", zh: "([^"]+)" \}[\s\S]*?image: "([^"]+)",(\s*imageLimited: true,)?/g;
const rows = [...catalog.matchAll(re)].map((m) => ({ slug: m[1], model: m[2], category: m[3], en: m[4], zh: m[5], image: m[6], limited: !!m[7] }));
const factory = readFileSync("src/data/factory-photos.ts", "utf8");
const fre = /file: "([^"]+)",\s*original: "([^"]+)",[\s\S]*?title: \{ en: "([^"]+)", zh: "([^"]+)" \}/g;
const frows = [...factory.matchAll(fre)].map((m) => ({ file: m[1], original: m[2], en: m[3], zh: m[4] }));
const list = (dir, ext = ".webp") => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : []);
const editorial = list("public/images/editorial");
const hero = list("public/images/hero");
const studio = list("public/images/studio");
const frames = list("public/images/hero/frames/d").length;

const md = `# Image manifest / 图片清单

Generated by \`node scripts/write-image-manifest-doc.mjs\`. Three kinds of imagery are used — never mixed up:

| Type | Source | Use | Can be replaced? |
|---|---|---|---|
| **Factory photographs** | Supplied by Yalilai, shot on site (HEIC → JPEG, resized, GPS/EXIF stripped, no retouching) | Factory tour, home gallery, about, quality | Only with other genuine Yalilai photos |
| **Catalogue photographs** | Product photographs from the reference catalogue supplied by the client, isolated on pure white (#FFFFFF) without altering the product; models with any brand mark or printed text on the product were excluded (see \`docs/catalog/\`) | Catalogue, collections, product pages, home sections | Yes — with the client's own approved photography (same file name, 4:5) |
| **Illustrative renderings** | Original procedural 3D renders made for this project (\`tools/product-renders\`), "YOUR BRAND" placeholder | Home hero, insights covers, Customization Studio | Yes |

## Factory photographs (${frows.length})

| File | Original file | Title (EN / 中文) |
|---|---|---|
${frows.map((f) => `| \`public/images/factory/${f.file}\` | ${f.original} | ${f.en} / ${f.zh} |`).join("\n")}

## Catalogue photographs (${rows.length} models)

1600 × 2000 px WebP masters (q90, metadata stripped); next/image serves AVIF/WebP derivatives per screen size.
Models marked *limited* come from small source photos (< 1000 px) and are shown without artificial enhancement.

| Model | Name (EN / 中文) | Category | File | Note |
|---|---|---|---|---|
${rows.map((r) => `| ${r.model} | ${r.en} / ${r.zh} | ${r.category} | \`public${r.image}\` | ${r.limited ? "limited source resolution" : ""} |`).join("\n")}

## Illustrative renderings

- Hero cut-outs: ${hero.map((f) => `\`public/images/hero/${f}\``).join(", ") || "—"}
- Hero turntable sequence: ${frames} frames in \`public/images/hero/frames/{d,m}/\` (desktop / mobile crops) + \`poster.webp\`
- Insights covers: ${editorial.map((f) => `\`public/images/editorial/${f}\``).join(", ") || "—"}
- Customization Studio family thumbnails: ${studio.map((f) => `\`public/images/studio/${f}\``).join(", ") || "—"}

Renderings are labelled "Illustrative rendering" on the site and must not be presented as factory samples or stock.
`;
writeFileSync("docs/IMAGE-MANIFEST.md", md);
console.log(`docs/IMAGE-MANIFEST.md: ${rows.length} catalogue models, ${frows.length} factory photos`);

const shots = `# Photography shot list / 拍摄清单

Use this brief to replace catalogue photographs with Yalilai's own photography of approved samples
(recommended before public launch — see the approval checklist in \`docs/catalog/CATALOG-REPORT.md\`).

## Art direction

- Background: pure white (#FFFFFF), seamless; soft contact shadow only.
- Light: large overhead softbox + two strip lights at 45° behind for crisp barrel edges; polarise metallic barrels.
- Camera: 100 mm macro equivalent, f/11, straight-on front view, product upright and centred, 4:5 portrait
  crop, 4000 px+ source, sRGB export. Keep the same scale for all pens of one category.
- Set per model: closed (capped) + open (tip shown) side by side, like the current reference photos;
  optional macro crops of the tip / brush / spoolie.
- Branding: blank barrels or the client's own approved logo only — never third-party marks.

## Models (${rows.length})

| Model | Shot | Priority |
|---|---|---|
${rows.map((r) => `| ${r.model} — ${r.en} | closed + open, tip macro | ${r.limited ? "high (source photo is small)" : r.category.includes("eyebrow") || r.category.includes("eyeliner") ? "high (headline range)" : "normal"} |`).join("\n")}
`;
writeFileSync("docs/PHOTOGRAPHY-SHOT-LIST.md", shots);
console.log("docs/PHOTOGRAPHY-SHOT-LIST.md written");
